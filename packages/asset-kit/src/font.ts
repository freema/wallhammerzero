const ROWS = new Map<string, readonly string[]>();
for (const [character, text] of Object.entries(GLYPHS)) {
  const rows = text.split(" ");
  if (rows.length !== GLYPH_H || rows.some((row) => row.length !== GLYPH_W)) {
    throw new Error(`font: the glyph ${JSON.stringify(character)} is not ${GLYPH_W} x ${GLYPH_H}`);
  }
  ROWS.set(character, rows);
}

/** The rows of a character's glyph; `?` for a character the font does not have. */
export function glyphRows(character: string): readonly string[] {
  return ROWS.get(character) ?? ROWS.get(character.toUpperCase()) ?? (ROWS.get("?") as readonly string[]);
}

/** The width of a line of text in pixels at an integer scale. */
export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale;
}

/** The height of a line of text in pixels at an integer scale. */
export function textHeight(scale: number): number {
  return GLYPH_H * scale;
}
